"""Seed archive and release-input integrity checks (BUG-089, DEV-053 P04).

The trusted seed digest comes from an explicit release record
(``docs/seed_package.json``) that lives beside the sources and outside the seed
archive, so a rebuilt or tampered archive can never declare its own expected
digest. Every check raises ``ValueError`` before any archive, seed library or
release file is written.
"""

from __future__ import annotations

import ast
import hashlib
import json
import re
import zipfile
from pathlib import Path, PurePosixPath

from creo_mechdog.seed_distribution import seed_file_bytes

TRUSTED_RECORD = "docs/seed_package.json"
SEED_LIBRARY = "seed_library"
SEED_MANIFEST = "seed_manifest.json"
DOCUMENTATION_MANIFEST = "docs/seed_manifest.json"
POSTCHECK = "docs/development/RELEASE-POSTCHECK-2026-11-07.md"

# DEV-083 (0.22.0 feedback): 0.22.0 and 0.23.0 were tagged before their
# POSTCHECK/release records were backfilled, so the distributed source.zip still
# carried a placeholder. The record gate starts with 0.23.1 and refuses to
# produce or verify such a package.
RECORDS_ENFORCED_FROM = (0, 23, 1)
_PLACEHOLDERS = ("待回填", "待发布后回填", "发布后在此段回填", "PENDING", "准备态")

RELEASE_ASSET_NAME = "MCP_CREO_MechDog"
_HEX = set("0123456789abcdefABCDEF")

SEED_FILE_PATTERN = r"[A-Za-z0-9_]{1,31}\.prt\.\d+"
SEED_TEXT_SUFFIXES = {".md", ".json", ".py"}
_DIGEST_PATTERN = re.compile(r"[a-f0-9]{64}")
_LINK_PATTERN = re.compile(r"!?\[[^\]]*\]\(([^)\s]+)\)")
_README_TITLE_PATTERN = re.compile(r"^#\s+MCP_CREO_MechDog\s+(\S+)", re.MULTILINE)
_README_CURRENT_PATTERN = re.compile(r"当前正式版\s*\*\*([^*]+)\*\*")


def _read_json_bytes(data: bytes, origin: str) -> dict:
    try:
        value = json.loads(data.decode("utf-8-sig"))
    except (UnicodeDecodeError, ValueError) as error:
        raise ValueError(f"{origin} is not readable JSON: {error}") from error
    if not isinstance(value, dict):
        raise ValueError(f"{origin} is not a JSON object")
    return value


def _read_json(path: Path) -> dict:
    try:
        data = path.read_bytes()
    except OSError as error:
        raise ValueError(f"Cannot read {path}: {error}") from error
    return _read_json_bytes(data, str(path))


def expected_assets(version: str) -> list[str]:
    """Return the four asset names a release of ``version`` must publish."""
    source = f"{RELEASE_ASSET_NAME}-{version}-source.zip"
    seed = f"{RELEASE_ASSET_NAME}-{version}-seed-library.zip"
    return [source, f"{source}.sha256", seed, f"{seed}.sha256"]


def read_sidecar(path: Path) -> tuple[str, str]:
    """Return ``(digest, zip_name)`` from a one-line ``sha256sum`` style sidecar.

    ``splitlines`` keeps reading sidecars written by older releases with CRLF
    line endings; only the generated bytes are now fixed to ASCII plus LF.
    """
    path = Path(path)
    try:
        text = path.read_text(encoding="ascii")
    except UnicodeDecodeError as error:
        raise ValueError(f"{path.name}: sidecar is not ASCII text ({error.reason})") from None
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    if len(lines) != 1:
        raise ValueError(f"{path.name}: sidecar must contain exactly one non-empty line")
    parts = lines[0].split()
    if len(parts) != 2:
        raise ValueError(f"{path.name}: expected '<64-hex SHA256>  <file name>'")
    digest, target = parts
    if len(digest) != 64 or not set(digest) <= _HEX:
        raise ValueError(f"{path.name}: sidecar digest is not a 64-character SHA256")
    return digest.lower(), target


def write_sidecar(path: Path, digest: str, archive_name: str) -> None:
    """Write a ``sha256sum`` style sidecar as ASCII bytes with LF line endings."""
    with Path(path).open("w", encoding="ascii", newline="\n") as handle:
        handle.write(f"{digest}  {archive_name}\n")


def validate_asset_paths(paths: list[Path], version: str) -> list[str]:
    """Return every problem that makes ``paths`` unusable as release assets.

    Unlike :func:`validate_directory` the four files may live in different
    directories, which is how the source and seed packagers produce them.
    """
    expected = expected_assets(version)
    files = {path.name: path for path in (Path(path) for path in paths) if path.is_file()}
    present = set(files)
    problems = [f"missing release asset: {name}" for name in expected if name not in present]
    problems.extend(f"unexpected release asset: {name}" for name in sorted(present - set(expected)))
    for name in expected:
        if not name.endswith(".sha256") or name not in present:
            continue
        zip_name = name[: -len(".sha256")]
        if zip_name not in present:
            continue
        try:
            digest, target = read_sidecar(files[name])
        except ValueError as error:
            problems.append(str(error))
            continue
        if target != zip_name:
            problems.append(f"{name}: sidecar names {target}, expected {zip_name}")
        actual = hashlib.sha256(files[zip_name].read_bytes()).hexdigest()
        if actual != digest:
            problems.append(f"{name}: sidecar {digest} differs from {zip_name} {actual}")
    return problems


def validate_directory(directory: Path, version: str) -> list[str]:
    """Return every problem that makes ``directory`` unusable as release assets."""
    directory = Path(directory)
    paths = list(directory.iterdir()) if directory.is_dir() else []
    return validate_asset_paths(paths, version)


def seed_library_files(root: Path) -> list[Path]:
    """Seed library members that belong to the distributed seed archive.

    This is the single source of truth for the seed allowlist: the seed packager
    and the release gate must agree on exactly the same member set.
    """
    library = Path(root) / SEED_LIBRARY
    if not library.is_dir():
        return []
    files = sorted(
        path
        for path in library.rglob("*")
        if path.is_file()
        and (
            path.suffix in SEED_TEXT_SUFFIXES
            or path.name == "LICENSE"
            or re.fullmatch(SEED_FILE_PATTERN, path.name)
        )
    )
    for path in files:
        if path.is_symlink():
            raise ValueError(f"Seed library file is an unexpected symlink: {path}")
    return files


def trusted_seed_package(root: Path) -> dict:
    """The explicit release record naming the trusted seed archive digest."""
    path = Path(root) / TRUSTED_RECORD
    if not path.is_file():
        raise ValueError(
            f"Trusted seed package record is missing: {path}; build the seed archive and "
            "backfill its SHA256 into this record before packaging source"
        )
    record = _read_json(path)
    version = record.get("compatible_server_version")
    digest = record.get("seed_archive_sha256")
    if not isinstance(version, str) or not version.strip():
        raise ValueError(f"{TRUSTED_RECORD} has no compatible_server_version")
    if not isinstance(digest, str) or not _DIGEST_PATTERN.fullmatch(digest):
        raise ValueError(f"{TRUSTED_RECORD} has no valid seed_archive_sha256")
    return {
        "compatible_server_version": version.strip(),
        "seed_archive_sha256": digest,
        "seed_archive_name": record.get("seed_archive_name"),
        "record": str(path),
    }


def trusted_seed_archive_digest(root: Path) -> str:
    """The trusted SHA256 of the seed archive published with this release."""
    return str(trusted_seed_package(root)["seed_archive_sha256"])


def read_version(root: Path) -> str:
    """The version declared by the source tree at ``root``."""
    path = Path(root) / "version.py"
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except OSError as error:
        raise ValueError(f"Cannot read {path}: {error}") from error
    except SyntaxError as error:
        raise ValueError(f"{path} is not readable Python: {error}") from error
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        targets = [target for target in node.targets if isinstance(target, ast.Name)]
        if not any(target.id == "VERSION" for target in targets):
            continue
        try:
            value = ast.literal_eval(node.value)
        except ValueError as error:
            raise ValueError(f"{path} does not declare a literal VERSION") from error
        if isinstance(value, str) and value.strip():
            return value.strip()
    raise ValueError(f"{path} does not declare VERSION")


def readme_versions(root: Path) -> dict:
    """The version numbers the public README claims for this release."""
    path = Path(root) / "README.md"
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as error:
        raise ValueError(f"Cannot read {path}: {error}") from error
    title = _README_TITLE_PATTERN.search(text)
    current = _README_CURRENT_PATTERN.search(text)
    return {
        "title": title.group(1) if title else None,
        "current": current.group(1) if current else None,
    }


def seed_archive_prefix(version: str) -> str:
    """The single top-level directory every seed archive member lives under."""
    return f"MCP_CREO_MechDog-{version}-seed-library/"


def archive_members(archive: zipfile.ZipFile) -> dict[str, bytes]:
    """Read every archive member, rejecting unsafe or duplicated member paths."""
    members: dict[str, bytes] = {}
    for info in archive.infolist():
        if info.is_dir():
            continue
        parts = PurePosixPath(info.filename)
        if (
            parts.is_absolute()
            or ".." in parts.parts
            or "\\" in info.filename
            or len(parts.parts) < 2
        ):
            raise ValueError(f"Unsafe seed archive path: {info.filename}")
        if info.filename in members:
            raise ValueError(f"Duplicate seed archive member: {info.filename}")
        members[info.filename] = archive.read(info)
    return members


def validate_seed_archive(root: Path, seed_archive: Path) -> dict[str, object]:
    """Check one seed archive against the trusted record and this source tree.

    Rejects a modified archive, an unsafe or unexpected member path, a manifest
    that differs from the repository, a foreign version and native seed bytes
    that do not match the published SHA256 values.
    """
    root = Path(root)
    archive_path = Path(seed_archive)
    if not archive_path.is_file():
        raise ValueError(f"Seed archive does not exist: {archive_path}")
    trusted = trusted_seed_package(root)
    version = read_version(root)
    if version != trusted["compatible_server_version"]:
        raise ValueError(
            f"version.py declares {version} but the trusted seed package record declares "
            f"{trusted['compatible_server_version']}"
        )
    digest = hashlib.sha256(archive_path.read_bytes()).hexdigest()
    if digest != trusted["seed_archive_sha256"]:
        raise ValueError(
            "Seed archive SHA256 differs from the trusted seed package record: "
            f"archive {digest}, trusted {trusted['seed_archive_sha256']}"
        )
    prefix = seed_archive_prefix(version)
    try:
        archive = zipfile.ZipFile(archive_path)
    except zipfile.BadZipFile as error:
        raise ValueError(f"Seed archive is not a readable ZIP: {error}") from error
    with archive:
        if archive.testzip() is not None:
            raise ValueError("Seed archive CRC check failed")
        members = archive_members(archive)
    outside = sorted(name for name in members if not name.startswith(prefix))
    if outside:
        raise ValueError(f"Seed archive contains a file outside {prefix}: {outside[0]}")
    manifest_name = prefix + SEED_MANIFEST
    if manifest_name not in members:
        raise ValueError(f"Seed archive does not contain {manifest_name}")
    manifest = _read_json_bytes(members[manifest_name], manifest_name)
    repository_manifest = _read_json(root / DOCUMENTATION_MANIFEST)
    if manifest != repository_manifest:
        raise ValueError("Seed archive manifest differs from the repository seed manifest")
    if manifest.get("compatible_server_version") != version:
        raise ValueError(
            f"Seed archive manifest version {manifest.get('compatible_server_version')} "
            f"differs from version.py {version}"
        )
    for entry in manifest.get("seeds", []):
        name = prefix + str(entry.get("relative_path", ""))
        if name not in members:
            raise ValueError(f"Seed archive is missing {entry.get('relative_path')}")
        actual = hashlib.sha256(members[name]).hexdigest()
        if actual != entry.get("sha256"):
            raise ValueError(
                f"Seed archive bytes for {entry.get('name')} differ from the published SHA256"
            )
    library = root / SEED_LIBRARY
    if library.is_dir():
        library_manifest = _read_json(library / SEED_MANIFEST)
        if library_manifest != repository_manifest:
            raise ValueError(
                "Repository seed manifests differ: docs/seed_manifest.json and "
                "seed_library/seed_manifest.json"
            )
    return {
        "seed_archive": str(archive_path),
        "seed_archive_sha256": digest,
        "compatible_server_version": version,
        "seed_count": len(manifest.get("seeds", [])),
        "trusted_record": trusted["record"],
    }


def assert_repo_record_matches(
    root: Path, seed_archive: Path, *, record_path: Path | None = None
) -> dict[str, object]:
    """Check a freshly built archive against this tree's own release record.

    DEV-061: the packer already refuses a mismatching archive, but nothing
    compared the checked-in ``docs/seed_package.json`` with a rebuild of the
    current tree, so a forgotten backfill only surfaced at packaging time.
    Only the digest and the declared version are compared here; member-level
    checks stay in :func:`validate_seed_archive`.
    """
    root = Path(root)
    archive_path = Path(seed_archive)
    if not archive_path.is_file():
        raise ValueError(f"Seed archive does not exist: {archive_path}")
    path = Path(record_path) if record_path is not None else root / TRUSTED_RECORD
    if not path.is_file():
        raise ValueError(f"Cannot read {path}: the trusted seed package record is missing")
    record = _read_json(path)
    version = read_version(root)
    declared = record.get("compatible_server_version")
    if declared != version:
        raise ValueError(
            f"version.py declares {version} but {TRUSTED_RECORD} declares {declared}; "
            "backfill docs/seed_package.json before packaging this release"
        )
    digest = hashlib.sha256(archive_path.read_bytes()).hexdigest()
    expected = record.get("seed_archive_sha256")
    if digest != expected:
        raise ValueError(
            f"Seed archive SHA256 {digest} differs from {TRUSTED_RECORD} "
            f"seed_archive_sha256 {expected}; backfill docs/seed_package.json with the rebuilt "
            "digest, rebuild once to confirm it is stable, then package the source"
        )
    return {
        "seed_archive": str(archive_path),
        "seed_archive_sha256": digest,
        "compatible_server_version": version,
        "record": str(path),
    }


def validate_release_inputs(root: Path, seed_archive: Path) -> dict[str, object]:
    """Check the release inputs before the public source package is written.

    The source version, both seed manifests, the README version sections and the
    seed archive must all describe one and the same release.
    """
    root = Path(root)
    version = read_version(root)
    readme = readme_versions(root)
    if readme["title"] != version:
        raise ValueError(
            f"README title version {readme['title']} differs from version.py {version}"
        )
    if readme["current"] != version:
        raise ValueError(
            f"README current release section {readme['current']} differs from version.py {version}"
        )
    documentation = _read_json(root / DOCUMENTATION_MANIFEST)
    library_root = root / SEED_LIBRARY
    if library_root.is_dir():
        library_manifest = _read_json(library_root / SEED_MANIFEST)
        if library_manifest != documentation:
            raise ValueError(
                "Repository seed manifests differ: docs/seed_manifest.json and "
                "seed_library/seed_manifest.json"
            )
    summary = validate_seed_archive(root, seed_archive)
    if library_root.is_dir():
        prefix = seed_archive_prefix(version)
        with zipfile.ZipFile(summary["seed_archive"]) as archive:
            members = archive_members(archive)
        expected = {
            prefix + path.relative_to(library_root).as_posix() for path in seed_library_files(root)
        }
        if set(members) != expected:
            missing = sorted(expected - set(members))
            extra = sorted(set(members) - expected)
            raise ValueError(
                "Seed archive members differ from the repository seed library: "
                f"missing {missing or 'none'}, unexpected {extra or 'none'}"
            )
        for path in seed_library_files(root):
            relative = path.relative_to(library_root).as_posix()
            if members[prefix + relative] != seed_file_bytes(path):
                raise ValueError(
                    f"Seed archive bytes for {relative} differ from the repository seed library"
                )
    return {
        **summary,
        "version": version,
        "readme_title_version": readme["title"],
        "readme_current_version": readme["current"],
        "manifest_seed_count": summary["seed_count"],
    }


def _release_version_tuple(version: str) -> tuple[int, int, int]:
    match = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", version.strip())
    if match is None:
        raise ValueError(f"Release version {version!r} is not MAJOR.MINOR.PATCH")
    return int(match.group(1)), int(match.group(2)), int(match.group(3))


def _postcheck_section(text: str, version: str) -> str | None:
    """The body of ``## v<version>`` in the POSTCHECK file, or ``None``."""
    lines = text.splitlines()
    header = f"## v{version}"
    start = None
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped == header or stripped.startswith((header + " ", header + "（", header + "(")):
            start = index + 1
            break
    if start is None:
        return None
    end = len(lines)
    for index in range(start, len(lines)):
        if lines[index].startswith("## "):
            end = index
            break
    return "\n".join(lines[start:end])


def _declared_version(text: str) -> str | None:
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return None
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        targets = [target for target in node.targets if isinstance(target, ast.Name)]
        if not any(target.id == "VERSION" for target in targets):
            continue
        try:
            value = ast.literal_eval(node.value)
        except ValueError:
            return None
        if isinstance(value, str) and value.strip():
            return value.strip()
    return None


def _work_item_status(backlog: str, work_id: str) -> str | None:
    """The status cell of ``work_id``'s table row in the main backlog."""
    for line in backlog.splitlines():
        stripped = line.strip()
        if not stripped.startswith("|"):
            continue
        cells = [cell.strip() for cell in stripped.strip("|").split("|")]
        if len(cells) < 3 or f"[{work_id}]" not in cells[0]:
            continue
        return cells[2]
    return None


#: Delivery-state vocabulary shared by the backlog, the work cards and the
#: per-ID table. Only these classes may be compared; a technical phrase such as
#: "已实现并实机验收" is not a delivery claim and stays ``other``.
_PARTIAL_MARKERS = ("部分交付", "待验收", "待复现", "已有修复", "观察中", "待核实")
_EXPLANATION_NONE = ("", "—", "-", "无", "无。")


def _status_class(text: str) -> str:
    """Normalize one status phrase to a comparable delivery class."""
    value = text.strip()
    if "其它 agent" in value:
        return "other"
    if "部分交付" in value:
        return "partial"
    if "已交付" in value and ("剩余" in value or "子项" in value):
        return "partial"
    if "已交付" in value:
        return "delivered"
    if "开发中" in value:
        return "developing"
    if "未排期" in value or "待规划" in value:
        return "unplanned"
    if any(marker in value for marker in _PARTIAL_MARKERS):
        return "partial"
    return "other"


def _split_row(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _is_separator(cells: list[str]) -> bool:
    return bool(cells) and all(re.fullmatch(r":?-{3,}:?", cell) for cell in cells if cell)


def _id_table(text: str) -> tuple[list[str], list[tuple[str, list[str]]]]:
    """The ``## 逐 ID 状态核对`` header and its ``(id, cells)`` rows."""
    lines = text.splitlines()
    start = None
    for index, line in enumerate(lines):
        if line.strip().startswith("## 逐 ID"):
            start = index + 1
            break
    if start is None:
        return [], []
    header: list[str] = []
    rows: list[tuple[str, list[str]]] = []
    for line in lines[start:]:
        stripped = line.strip()
        if stripped.startswith("## "):
            break
        if not stripped.startswith("|"):
            continue
        cells = _split_row(stripped)
        if not cells:
            continue
        if not header:
            header = cells
            continue
        if _is_separator(cells):
            continue
        match = re.search(r"\b[A-Z]+-\d+\b", cells[0])
        if match is not None:
            rows.append((match.group(0), cells))
    return header, rows


def _cell(header: list[str], cells: list[str], *names: str) -> str:
    for index, title in enumerate(header):
        if any(name in title for name in names) and index < len(cells):
            return cells[index]
    return ""


def _card_summary(card: str) -> str:
    for line in card.splitlines()[:12]:
        if "分类：" in line:
            return line.strip()
    return ""


def _card_status(card: str) -> str:
    """The bold status token on the card's ``分类：`` line.

    Card summaries continue with evidence sentences that often contain
    "已交付" for a sub-item; reading the whole line would misclassify a
    ``待复现`` card as delivered.
    """
    summary = _card_summary(card)
    if not summary:
        return ""
    match = re.search(r"\*\*([^*]+)\*\*", summary)
    return match.group(1) if match is not None else summary.split("。", 1)[0]


def _backlog_rows(backlog: str) -> list[tuple[str, list[str]]]:
    """``[ID](work-items/...)`` rows of the main backlog with at least 3 cells."""
    rows: list[tuple[str, list[str]]] = []
    for line in backlog.splitlines():
        stripped = line.strip()
        if not stripped.startswith("|"):
            continue
        cells = _split_row(stripped)
        if len(cells) < 3 or _is_separator(cells):
            continue
        if "work-items/" not in cells[0]:
            continue
        match = re.search(r"\[([A-Z]+-\d+)\]", cells[0])
        if match is not None:
            rows.append((match.group(1), cells))
    return rows


def _record_problems(
    text: str,
    version: str,
    origin: str,
    seed_digest: str | None,
    *,
    require_sidecar_note: bool,
) -> list[str]:
    """Problems in one POSTCHECK section or ``RELEASE-<version>.md`` record."""
    problems = []
    for name in expected_assets(version):
        if name not in text:
            problems.append(f"{origin}: missing release asset {name}")
    release_url = f"https://github.com/wudahua/MCP_CREO_MechDog/releases/tag/v{version}"
    if release_url not in text:
        problems.append(f"{origin}: missing Release URL {release_url}")
    if seed_digest is None:
        problems.append(f"{origin}: no trusted seed archive SHA256 to match")
    elif seed_digest not in text:
        problems.append(f"{origin}: missing seed archive SHA256 {seed_digest}")
    if _DIGEST_PATTERN.search(text) is None:
        problems.append(f"{origin}: missing a 64-character SHA256")
    for placeholder in _PLACEHOLDERS:
        if placeholder in text:
            problems.append(f"{origin}: contains placeholder {placeholder!r}")
    if require_sidecar_note and not re.search(
        r"摘要[^\n]{0,24}sidecar|sidecar[^\n]{0,24}摘要", text
    ):
        problems.append(f"{origin}: must state that the source.zip digest is in its sidecar")
    return problems


def _link_problems(text: str, origin: str, base_dir: str, exists) -> list[str]:
    """Broken relative links in one published document.

    Only file existence is checked; anchors and external URLs are skipped. A
    link that walks above the package root is rejected so ``../../outside`` can
    never pass on the author's machine.
    """
    problems = []
    for target in _LINK_PATTERN.findall(text):
        if target.startswith(("http://", "https://", "mailto:", "#", "/")):
            continue
        path = target.split("#", 1)[0].strip("<>")
        if not path:
            continue
        parts: list[str] | None = []
        for part in f"{base_dir}/{path}".split("/"):
            if part in ("", "."):
                continue
            if part == "..":
                if not parts:
                    problems.append(f"{origin}: link {target!r} escapes the package")
                    parts = None
                    break
                parts.pop()
            else:
                parts.append(part)
        if parts is None:
            continue
        name = "/".join(parts)
        if not exists(name):
            problems.append(f"{origin}: broken local link {target!r} -> {name}")
    return problems


def _work_item_problems(version: str, record: str, read, origin: str) -> list[str]:
    """Cross-check the release's per-ID table and every active delivery row."""
    backlog = read("docs/BACKLOG.md")
    if backlog is None:
        return [f"{origin}: missing docs/BACKLOG.md for the per-ID check"]
    header, rows = _id_table(record)
    if not rows:
        return [f"{origin}: RELEASE-{version}.md has no '逐 ID 状态核对' table rows"]
    problems = []
    checked = set()
    for work_id, cells in rows:
        checked.add(work_id)
        status = _work_item_status(backlog, work_id)
        if status is None:
            problems.append(f"{origin}: {work_id} is missing from docs/BACKLOG.md")
            continue
        card = read(f"docs/work-items/{work_id}.md")
        if card is None:
            problems.append(f"{origin}: missing docs/work-items/{work_id}.md")
            continue
        if version not in "\n".join(card.splitlines()[:12]):
            problems.append(
                f"{origin}: docs/work-items/{work_id}.md first 12 lines do not mention {version}"
            )
        explanation = _cell(header, cells, "差异说明")
        explained = explanation.strip() not in _EXPLANATION_NONE
        backlog_class = _status_class(status)
        for title in ("技术状态", "卡首页"):
            value = _cell(header, cells, title)
            if not value or _status_class(value) == "other":
                continue
            if _status_class(value) != backlog_class and not explained:
                problems.append(
                    f"{origin}: {work_id} {title} {value!r} differs from docs/BACKLOG.md {status!r}"
                )
        ledger_cell = _cell(header, cells, "主台账")
        if ledger_cell and ledger_cell.strip() != status.strip() and not explained:
            problems.append(
                f"{origin}: {work_id} 主台账 cell {ledger_cell!r} differs from "
                f"docs/BACKLOG.md {status!r}"
            )
        summary = _card_summary(card)
        if not summary:
            problems.append(
                f"{origin}: docs/work-items/{work_id}.md has no '分类：' line in its first 12 lines"
            )
        elif _status_class(_card_status(card)) != backlog_class and not explained:
            problems.append(
                f"{origin}: work card {work_id} says {summary!r} but docs/BACKLOG.md "
                f"says {status!r}"
            )
        if f"已交付 {version}" in " | ".join(cells) and backlog_class in (
            "developing",
            "unplanned",
        ):
            problems.append(
                f"{origin}: {work_id} claims 已交付 {version} but docs/BACKLOG.md says {status}"
            )
    for work_id, cells in _backlog_rows(backlog):
        if work_id in checked:
            continue
        status = cells[2]
        backlog_class = _status_class(status)
        if backlog_class not in ("partial", "delivered"):
            continue
        card = read(f"docs/work-items/{work_id}.md")
        if card is None:
            problems.append(
                f"{origin}: docs/work-items/{work_id}.md is missing for a {status!r} row"
            )
            continue
        summary = _card_summary(card)
        if summary and _status_class(_card_status(card)) != backlog_class:
            problems.append(
                f"{origin}: work card {work_id} says {summary!r} but docs/BACKLOG.md "
                f"says {status!r}"
            )
    return problems


def _version_problems(version: str, read, origin: str) -> list[str]:
    """The package's own version declarations must all agree."""
    problems = []
    source = read("version.py")
    if source is None:
        problems.append(f"{origin}: missing version.py")
    else:
        declared = _declared_version(source)
        if declared != version:
            problems.append(f"{origin}: version.py declares {declared}, expected {version}")
    readme = read("README.md")
    if readme is None:
        problems.append(f"{origin}: missing README.md")
    else:
        title = _README_TITLE_PATTERN.search(readme)
        current = _README_CURRENT_PATTERN.search(readme)
        if title is None or title.group(1) != version:
            problems.append(f"{origin}: README title is not {version}")
        if current is None or current.group(1) != version:
            problems.append(f"{origin}: README current release section is not {version}")
    for name in (DOCUMENTATION_MANIFEST, f"{SEED_LIBRARY}/{SEED_MANIFEST}"):
        text = read(name)
        if text is None:
            problems.append(f"{origin}: missing {name}")
            continue
        try:
            manifest = json.loads(text)
        except ValueError:
            problems.append(f"{origin}: {name} is not readable JSON")
            continue
        declared = manifest.get("compatible_server_version")
        if declared != version:
            problems.append(f"{origin}: {name} declares {declared}, expected {version}")
    return problems


def _records_problems(version: str, read, exists, origin: str) -> list[str]:
    problems = _version_problems(version, read, origin)
    seed_digest = None
    record = read(TRUSTED_RECORD)
    if record is None:
        problems.append(f"{origin}: missing {TRUSTED_RECORD}")
    else:
        try:
            seed_digest = json.loads(record).get("seed_archive_sha256")
        except ValueError:
            problems.append(f"{origin}: {TRUSTED_RECORD} is not readable JSON")
        if not isinstance(seed_digest, str) or _DIGEST_PATTERN.fullmatch(seed_digest) is None:
            problems.append(f"{origin}: {TRUSTED_RECORD} has no valid seed_archive_sha256")
            seed_digest = None
    postcheck = read(POSTCHECK)
    if postcheck is None:
        problems.append(f"{origin}: missing {POSTCHECK}")
    else:
        problems.extend(
            _link_problems(postcheck, f"{origin}:{POSTCHECK}", "docs/development", exists)
        )
        section = _postcheck_section(postcheck, version)
        if section is None:
            problems.append(f"{origin}: {POSTCHECK} has no '## v{version}' section")
        else:
            problems.extend(
                _record_problems(
                    section,
                    version,
                    f"{origin}:POSTCHECK v{version}",
                    seed_digest,
                    require_sidecar_note=False,
                )
            )
    notes = read(f"docs/RELEASE_NOTES_{version}.md")
    if notes is None:
        problems.append(f"{origin}: missing docs/RELEASE_NOTES_{version}.md")
    else:
        problems.extend(
            _link_problems(notes, f"{origin}:RELEASE_NOTES_{version}.md", "docs", exists)
        )
    release = read(f"docs/validation/RELEASE-{version}.md")
    if release is None:
        problems.append(f"{origin}: missing docs/validation/RELEASE-{version}.md")
    else:
        problems.extend(
            _record_problems(
                release,
                version,
                f"{origin}:RELEASE-{version}.md",
                seed_digest,
                require_sidecar_note=True,
            )
        )
        problems.extend(
            _link_problems(release, f"{origin}:RELEASE-{version}.md", "docs/validation", exists)
        )
        problems.extend(_work_item_problems(version, release, read, origin))
    return problems


def validate_release_records(
    version: str,
    source_zip: Path | None = None,
    root: Path | None = None,
) -> list[str]:
    """Problems that keep ``version`` from being packaged or published.

    DEV-083: 0.22.0 and 0.23.0 were tagged before their POSTCHECK and release
    records were backfilled, so the distributed ``source.zip`` carried a
    placeholder. From :data:`RECORDS_ENFORCED_FROM` on, the packager refuses to
    write such an archive and the remote check refuses to accept one. When
    ``source_zip`` is given, the same checks run against the archive's own copies
    and its version declarations must agree with ``version``. Versions before the
    enforcement point return no problems; their historical tags only get the
    four-asset check.
    """
    try:
        enforced = _release_version_tuple(version) >= RECORDS_ENFORCED_FROM
    except ValueError as error:
        return [str(error)]
    if not enforced:
        return []
    base: Path | None = None
    if root is not None:
        base = Path(root)
    elif source_zip is None:
        base = Path(__file__).resolve().parents[2]

    def read_tree(name: str) -> str | None:
        path = Path(base) / name
        if not path.is_file():
            return None
        return path.read_text(encoding="utf-8-sig")

    def exists_tree(name: str) -> bool:
        return (Path(base) / name).is_file()

    problems = (
        [] if base is None else _records_problems(version, read_tree, exists_tree, "source tree")
    )
    if source_zip is None:
        return problems
    archive_path = Path(source_zip)
    try:
        with zipfile.ZipFile(archive_path) as archive:
            members = archive_members(archive)
    except (OSError, zipfile.BadZipFile) as error:
        return problems + [f"source.zip is not a readable ZIP: {error}"]
    prefix = f"{RELEASE_ASSET_NAME}/"

    def read_archive(name: str) -> str | None:
        data = members.get(prefix + name)
        return None if data is None else data.decode("utf-8-sig")

    def exists_archive(name: str) -> bool:
        return prefix + name in members

    return problems + _records_problems(
        version, read_archive, exists_archive, f"{archive_path.name}"
    )
