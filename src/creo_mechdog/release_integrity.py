def _read_json_bytes(data: bytes, origin: str) -> dict:
    try:
        value = json.loads(data.decode("utf-8-sig"))
    except (UnicodeDecodeError, ValueError) as error:
        raise ValueError(f"{origin} is not readable JSON: {error}") from error
    if not isinstance(value, dict):
        raise ValueError(f"{origin} is not a JSON object")
    return value


def _read_json(path: Path) -> dict:
    try:
        data = path.read_bytes()
    except OSError as error:
        raise ValueError(f"Cannot read {path}: {error}") from error
    return _read_json_bytes(data, str(path))


def expected_assets(version: str) -> list[str]:
    """Return the four asset names a release of ``version`` must publish."""
    source = f"{RELEASE_ASSET_NAME}-{version}-source.zip"
    seed = f"{RELEASE_ASSET_NAME}-{version}-seed-library.zip"
    return [source, f"{source}.sha256", seed, f"{seed}.sha256"]


def read_sidecar(path: Path) -> tuple[str, str]:
    """Return ``(digest, zip_name)`` from a one-line ``sha256sum`` style sidecar.

    ``splitlines`` keeps reading sidecars written by older releases with CRLF
    line endings; only the generated bytes are now fixed to ASCII plus LF.
    """
    path = Path(path)
    try:
        text = path.read_text(encoding="ascii")
    except UnicodeDecodeError as error:
        raise ValueError(f"{path.name}: sidecar is not ASCII text ({error.reason})") from None
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    if len(lines) != 1:
        raise ValueError(f"{path.name}: sidecar must contain exactly one non-empty line")
    parts = lines[0].split()
    if len(parts) != 2:
        raise ValueError(f"{path.name}: expected '<64-hex SHA256>  <file name>'")
    digest, target = parts
    if len(digest) != 64 or not set(digest) <= _HEX:
        raise ValueError(f"{path.name}: sidecar digest is not a 64-character SHA256")
    return digest.lower(), target


def write_sidecar(path: Path, digest: str, archive_name: str) -> None:
    """Write a ``sha256sum`` style sidecar as ASCII bytes with LF line endings."""
    with Path(path).open("w", encoding="ascii", newline="\n") as handle:
        handle.write(f"{digest}  {archive_name}\n")


def validate_asset_paths(paths: list[Path], version: str) -> list[str]:
    """Return every problem that makes ``paths`` unusable as release assets.

    Unlike :func:`validate_directory` the four files may live in different
    directories, which is how the source and seed packagers produce them.
    """
    expected = expected_assets(version)
    files = {path.name: path for path in (Path(path) for path in paths) if path.is_file()}
    present = set(files)
    problems = [f"missing release asset: {name}" for name in expected if name not in present]
    problems.extend(f"unexpected release asset: {name}" for name in sorted(present - set(expected)))
    for name in expected:
        if not name.endswith(".sha256") or name not in present:
            continue
        zip_name = name[: -len(".sha256")]
        if zip_name not in present:
            continue
        try:
            digest, target = read_sidecar(files[name])
        except ValueError as error:
            problems.append(str(error))
            continue
        if target != zip_name:
            problems.append(f"{name}: sidecar names {target}, expected {zip_name}")
        actual = hashlib.sha256(files[zip_name].read_bytes()).hexdigest()
        if actual != digest:
            problems.append(f"{name}: sidecar {digest} differs from {zip_name} {actual}")
    return problems


def validate_directory(directory: Path, version: str) -> list[str]:
    """Return every problem that makes ``directory`` unusable as release assets."""
    directory = Path(directory)
    paths = list(directory.iterdir()) if directory.is_dir() else []
    return validate_asset_paths(paths, version)


def body_check_enforced(version: str) -> bool:
    """Whether the Release body self-proof gate applies to ``version``.

    See :data:`BODY_CHECK_ENFORCED_FROM`. Releases published before the gate
    existed keep their historical bodies; the gate only refuses new releases.
    """
    try:
        return _release_version_tuple(version) >= BODY_CHECK_ENFORCED_FROM
    except ValueError:
        return False


def validate_release_body(body: str, version: str, sidecar_digests: dict[str, str]) -> list[str]:
    """Problems that keep a GitHub Release body from proving its own digests.

    The body must name all four shipped assets and tell the reader that the
    source digest is recorded in its sidecar (DEV-097: 0.32.0/0.33.0 dropped
    both, leaving the digests discoverable only from the in-package record).
    ``sidecar_digests`` maps each shipped ZIP name to the lowercase SHA256 its
    sidecar actually records; every 64-hex value the body states must be one of
    those real digests, and a value that disagrees is a mismatch.
    """
    problems = []
    for name in expected_assets(version):
        if name not in body:
            problems.append(f"release body is missing asset name: {name}")
    if _SIDECAR_GUIDANCE_PATTERN.search(body) is None:
        problems.append("release body must state that the source digest is recorded in its sidecar")
    actual = {digest.lower() for digest in sidecar_digests.values()}
    for match in _DIGEST_PATTERN.findall(body):
        if match.lower() not in actual:
            problems.append(f"release body states SHA256 {match} which does not match any sidecar")
    return problems


def seed_library_files(root: Path) -> list[Path]:
    """Seed library members that belong to the distributed seed archive.

    This is the single source of truth for the seed allowlist: the seed packager
    and the release gate must agree on exactly the same member set.
    """
    library = Path(root) / SEED_LIBRARY
    if not library.is_dir():
        return []
    files = sorted(
        path
        for path in library.rglob("*")
        if path.is_file()
        and (
            path.suffix in SEED_TEXT_SUFFIXES
            or path.name == "LICENSE"
            or re.fullmatch(SEED_FILE_PATTERN, path.name)
        )
    )
    for path in files:
        if path.is_symlink():
            raise ValueError(f"Seed library file is an unexpected symlink: {path}")
    return files


def template_library_files(root: Path) -> list[Path]:
    """Element tree templates that belong to the source release.

    ``TEMPLATE_MANIFEST`` is the allowlist: every template it names must exist
    with the declared size and SHA256, and a file the manifest does not name is
    not shipped. A template without its provenance record would let a client
    apply an element tree nobody measured, which is exactly what BUG-123 spent a
    live run establishing.
    """
    library = Path(root) / TEMPLATE_LIBRARY
    manifest_path = Path(root) / TEMPLATE_MANIFEST
    if not manifest_path.is_file():
        raise ValueError(
            f"Element tree template manifest is missing: {manifest_path}; export a template "
            "and record its digest before packaging source"
        )
    manifest = _read_json(manifest_path)
    entries = manifest.get("templates")
    if not isinstance(entries, list) or not entries:
        raise ValueError(f"{TEMPLATE_MANIFEST} names no templates")
    files = [manifest_path]
    seen: set[str] = set()
    for entry in entries:
        if not isinstance(entry, dict):
            raise ValueError(f"{TEMPLATE_MANIFEST} has a template entry that is not an object")
        name = entry.get("file")
        if not isinstance(name, str) or not name or PurePosixPath(name).name != name:
            raise ValueError(f"{TEMPLATE_MANIFEST} has an invalid template file name: {name!r}")
        if name in seen:
            raise ValueError(f"{TEMPLATE_MANIFEST} names {name} more than once")
        seen.add(name)
        path = library / name
        if not path.is_file() or path.is_symlink():
            raise ValueError(f"Manifest template is missing or is a symlink: {path}")
        data = path.read_bytes()
        declared = entry.get("sha256")
        if not isinstance(declared, str) or not _DIGEST_PATTERN.fullmatch(declared):
            raise ValueError(f"{TEMPLATE_MANIFEST} has no valid sha256 for {name}")
        digest = hashlib.sha256(data).hexdigest()
        if digest != declared:
            raise ValueError(
                f"Template {name} is {digest} but the manifest declares {declared}; re-export "
                "the template instead of shipping changed bytes"
            )
        declared_bytes = entry.get("bytes")
        if declared_bytes is not None and declared_bytes != len(data):
            raise ValueError(
                f"Template {name} is {len(data)} bytes but the manifest declares {declared_bytes}"
            )
        files.append(path)
    return files


def panel_profile_library_files(root: Path | None = None) -> list[Path]:
    """Resident-panel UI profiles that belong to the source release.

    ``templates/panel/manifest.json`` is the allowlist, exactly as the element
    tree manifest is: the shipped set is the manifest plus every certification
    record it references, and a file nobody references is not shipped. The rules
    that decide what a profile is — command digest, certification presence,
    certification digest, and the ``profile_digest`` binding — stay in
    :mod:`creo_mechdog.panel_profiles`; this gate only turns that module's
    refusal into a packaging failure, so the two can never disagree about what
    an admissible profile is.

    An empty ``profiles`` list is valid and ships the manifest alone. That is
    the currently shipped state (no profile has been accepted on a target host
    yet) and it is deliberately closed rather than absent: the manifest is what
    lets admission report "no certified profile" instead of replaying command
    text nobody measured.
    """
    base = Path(root) if root is not None else panel_profiles.ROOT
    try:
        profiles = panel_profiles.profiles(base)
    except panel_profiles.PanelProfileError as error:
        raise ValueError(f"Panel profile library is not distributable: {error}") from error
    manifest = base / panel_profiles.MANIFEST
    files = [manifest]
    library = (base / panel_profiles.LIBRARY).resolve()
    for profile in profiles:
        record = profile.certification
        if record is None:
            continue
        path = base / panel_profiles.CERTIFICATIONS / record["file"]
        if not path.is_file() or path.is_symlink():
            raise ValueError(f"Panel certification is missing or is a symlink: {path}")
        if not path.resolve().is_relative_to(library):
            raise ValueError(
                f"Panel certification escapes {panel_profiles.LIBRARY}: {path}; evidence "
                "outside the library is not part of this release"
            )
        files.append(path)
    # The recording a profile was frozen from ships with it. An admissible profile
    # whose evidence stayed behind would reach a client as command text nobody can
    # re-read, which is exactly the claim this library exists to prevent.
    try:
        document = json.loads(manifest.read_text(encoding="utf-8-sig"))
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError(f"Panel profile manifest cannot be read: {manifest} ({error})") from error
    recordings = document.get("recordings") or {}
    if not isinstance(recordings, dict):
        raise ValueError(f"{panel_profiles.MANIFEST}.recordings must be an object")
    for name, entry in recordings.items():
        if not isinstance(entry, dict) or not isinstance(entry.get("file"), str):
            raise ValueError(f"{panel_profiles.MANIFEST}.recordings[{name!r}] must name a file")
        path = base / panel_profiles.LIBRARY / entry["file"]
        if not path.is_file() or path.is_symlink():
            raise ValueError(f"Panel recording is missing or is a symlink: {path}")
        if not path.resolve().is_relative_to(library):
            raise ValueError(
                f"Panel recording escapes {panel_profiles.LIBRARY}: {path}; evidence outside "
                "the library is not part of this release"
            )
        declared = str(entry.get("sha256") or "").lower()
        if hashlib.sha256(path.read_bytes()).hexdigest() != declared:
            raise ValueError(
                f"Panel recording {path.name} does not match the digest "
                f"{panel_profiles.MANIFEST} declares; a changed recording invalidates the "
                "profile it was frozen from"
            )
        files.append(path)
    return files


def trusted_seed_package(root: Path) -> dict:
    """The explicit release record naming the trusted seed archive digest."""
    path = Path(root) / TRUSTED_RECORD
    if not path.is_file():
        raise ValueError(
            f"Trusted seed package record is missing: {path}; build the seed archive and "
            "backfill its SHA256 into this record before packaging source"
        )
    record = _read_json(path)
    version = record.get("compatible_server_version")
    digest = record.get("seed_archive_sha256")
    if not isinstance(version, str) or not version.strip():
        raise ValueError(f"{TRUSTED_RECORD} has no compatible_server_version")
    if not isinstance(digest, str) or not _DIGEST_PATTERN.fullmatch(digest):
        raise ValueError(f"{TRUSTED_RECORD} has no valid seed_archive_sha256")
    return {
        "compatible_server_version": version.strip(),
        "seed_archive_sha256": digest,
        "seed_archive_name": record.get("seed_archive_name"),
        "record": str(path),
    }


def trusted_seed_archive_digest(root: Path) -> str:
    """The trusted SHA256 of the seed archive published with this release."""
    return str(trusted_seed_package(root)["seed_archive_sha256"])


def read_version(root: Path) -> str:
    """The version declared by the source tree at ``root``."""
    path = Path(root) / "version.py"
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except OSError as error:
        raise ValueError(f"Cannot read {path}: {error}") from error
    except SyntaxError as error:
        raise ValueError(f"{path} is not readable Python: {error}") from error
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        targets = [target for target in node.targets if isinstance(target, ast.Name)]
        if not any(target.id == "VERSION" for target in targets):
            continue
        try:
            value = ast.literal_eval(node.value)
        except ValueError as error:
            raise ValueError(f"{path} does not declare a literal VERSION") from error
        if isinstance(value, str) and value.strip():
            return value.strip()
    raise ValueError(f"{path} does not declare VERSION")


def readme_versions(root: Path) -> dict:
    """The version numbers the public README claims for this release."""
    path = Path(root) / "README.md"
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as error:
        raise ValueError(f"Cannot read {path}: {error}") from error
    title = _README_TITLE_PATTERN.search(text)
    current = _README_CURRENT_PATTERN.search(text)
    return {
        "title": title.group(1) if title else None,
        "current": current.group(1) if current else None,
    }


def seed_archive_prefix(version: str) -> str:
    """The single top-level directory every seed archive member lives under."""
    return f"MCP_CREO_MechDog-{version}-seed-library/"


def archive_members(archive: zipfile.ZipFile) -> dict[str, bytes]:
    """Read every archive member, rejecting unsafe or duplicated member paths."""
    members: dict[str, bytes] = {}
    for info in archive.infolist():
        if info.is_dir():
            continue
        parts = PurePosixPath(info.filename)
        if (
            parts.is_absolute()
            or ".." in parts.parts
            or "\\" in info.filename
            or len(parts.parts) < 2
        ):
            raise ValueError(f"Unsafe seed archive path: {info.filename}")
        if info.filename in members:
            raise ValueError(f"Duplicate seed archive member: {info.filename}")
        members[info.filename] = archive.read(info)
    return members


def validate_seed_archive(root: Path, seed_archive: Path) -> dict[str, object]:
    """Check one seed archive against the trusted record and this source tree.

    Rejects a modified archive, an unsafe or unexpected member path, a manifest
    that differs from the repository, a foreign version and native seed bytes
    that do not match the published SHA256 values.
    """
    root = Path(root)
    archive_path = Path(seed_archive)
    if not archive_path.is_file():
        raise ValueError(f"Seed archive does not exist: {archive_path}")
    trusted = trusted_seed_package(root)
    version = read_version(root)
    if version != trusted["compatible_server_version"]:
        raise ValueError(
            f"version.py declares {version} but the trusted seed package record declares "
            f"{trusted['compatible_server_version']}"
        )
    digest = hashlib.sha256(archive_path.read_bytes()).hexdigest()
    if digest != trusted["seed_archive_sha256"]:
        raise ValueError(
            "Seed archive SHA256 differs from the trusted seed package record: "
            f"archive {digest}, trusted {trusted['seed_archive_sha256']}"
        )
    prefix = seed_archive_prefix(version)
    try:
        archive = zipfile.ZipFile(archive_path)
    except zipfile.BadZipFile as error:
        raise ValueError(f"Seed archive is not a readable ZIP: {error}") from error
    with archive:
        if archive.testzip() is not None:
            raise ValueError("Seed archive CRC check failed")
        members = archive_members(archive)
    outside = sorted(name for name in members if not name.startswith(prefix))
    if outside:
        raise ValueError(f"Seed archive contains a file outside {prefix}: {outside[0]}")
    manifest_name = prefix + SEED_MANIFEST
    if manifest_name not in members:
        raise ValueError(f"Seed archive does not contain {manifest_name}")
    manifest = _read_json_bytes(members[manifest_name], manifest_name)
    repository_manifest = _read_json(root / DOCUMENTATION_MANIFEST)
    if manifest != repository_manifest:
        raise ValueError("Seed archive manifest differs from the repository seed manifest")
    if manifest.get("compatible_server_version") != version:
        raise ValueError(
            f"Seed archive manifest version {manifest.get('compatible_server_version')} "
            f"differs from version.py {version}"
        )
    for entry in manifest.get("seeds", []):
        name = prefix + str(entry.get("relative_path", ""))
        if name not in members:
            raise ValueError(f"Seed archive is missing {entry.get('relative_path')}")
        actual = hashlib.sha256(members[name]).hexdigest()
        if actual != entry.get("sha256"):
            raise ValueError(
                f"Seed archive bytes for {entry.get('name')} differ from the published SHA256"
            )
    library = root / SEED_LIBRARY
    if library.is_dir():
        library_manifest = _read_json(library / SEED_MANIFEST)
        if library_manifest != repository_manifest:
            raise ValueError(
                "Repository seed manifests differ: docs/seed_manifest.json and "
                "seed_library/seed_manifest.json"
            )
    return {
        "seed_archive": str(archive_path),
        "seed_archive_sha256": digest,
        "compatible_server_version": version,
        "seed_count": len(manifest.get("seeds", [])),
        "trusted_record": trusted["record"],
    }


def assert_repo_record_matches(
    root: Path, seed_archive: Path, *, record_path: Path | None = None
) -> dict[str, object]:
    """Check a freshly built archive against this tree's own release record.

    DEV-061: the packer already refuses a mismatching archive, but nothing
    compared the checked-in ``docs/seed_package.json`` with a rebuild of the
    current tree, so a forgotten backfill only surfaced at packaging time.
    Only the digest and the declared version are compared here; member-level
    checks stay in :func:`validate_seed_archive`.
    """
    root = Path(root)
    archive_path = Path(seed_archive)
    if not archive_path.is_file():
        raise ValueError(f"Seed archive does not exist: {archive_path}")
    path = Path(record_path) if record_path is not None else root / TRUSTED_RECORD
    if not path.is_file():
        raise ValueError(f"Cannot read {path}: the trusted seed package record is missing")
    record = _read_json(path)
    version = read_version(root)
    declared = record.get("compatible_server_version")
    if declared != version:
        raise ValueError(
            f"version.py declares {version} but {TRUSTED_RECORD} declares {declared}; "
            "backfill docs/seed_package.json before packaging this release"
        )
    digest = hashlib.sha256(archive_path.read_bytes()).hexdigest()
    expected = record.get("seed_archive_sha256")
    if digest != expected:
        raise ValueError(
            f"Seed archive SHA256 {digest} differs from {TRUSTED_RECORD} "
            f"seed_archive_sha256 {expected}; backfill docs/seed_package.json with the rebuilt "
            "digest, rebuild once to confirm it is stable, then package the source"
        )
    return {
        "seed_archive": str(archive_path),
        "seed_archive_sha256": digest,
        "compatible_server_version": version,
        "record": str(path),
    }


def validate_release_inputs(root: Path, seed_archive: Path) -> dict[str, object]:
    """Check the release inputs before the public source package is written.

    The source version, both seed manifests, the README version sections, the
    seed archive, the element tree templates and the resident-panel profile
    library (BUG-120/D1) must all describe one and the same release.
    """
    root = Path(root)
    version = read_version(root)
    readme = readme_versions(root)
    if readme["title"] != version:
        raise ValueError(
            f"README title version {readme['title']} differs from version.py {version}"
        )
    if readme["current"] != version:
        raise ValueError(
            f"README current release section {readme['current']} differs from version.py {version}"
        )
    documentation = _read_json(root / DOCUMENTATION_MANIFEST)
    library_root = root / SEED_LIBRARY
    if library_root.is_dir():
        library_manifest = _read_json(library_root / SEED_MANIFEST)
        if library_manifest != documentation:
            raise ValueError(
                "Repository seed manifests differ: docs/seed_manifest.json and "
                "seed_library/seed_manifest.json"
            )
    summary = validate_seed_archive(root, seed_archive)
    if library_root.is_dir():
        prefix = seed_archive_prefix(version)
        with zipfile.ZipFile(summary["seed_archive"]) as archive:
            members = archive_members(archive)
        expected = {
            prefix + path.relative_to(library_root).as_posix() for path in seed_library_files(root)
        }
        if set(members) != expected:
            missing = sorted(expected - set(members))
            extra = sorted(set(members) - expected)
            raise ValueError(
                "Seed archive members differ from the repository seed library: "
                f"missing {missing or 'none'}, unexpected {extra or 'none'}"
            )
        for path in seed_library_files(root):
            relative = path.relative_to(library_root).as_posix()
            if members[prefix + relative] != seed_file_bytes(path):
                raise ValueError(
                    f"Seed archive bytes for {relative} differ from the repository seed library"
                )
    # BUG-123: the source package now carries element tree templates, so the
    # manifest must match the bytes on disk before anything is written.
    template_count = len(template_library_files(root)) - 1
    # BUG-120/D1: the resident-panel profile library ships the same way, as the
    # manifest plus the certification records it references. A missing manifest,
    # a referenced record that is gone or changed, or a path outside
    # templates/panel refuses the package instead of reaching a client.
    panel_files = panel_profile_library_files(root)
    return {
        **summary,
        "version": version,
        "readme_title_version": readme["title"],
        "readme_current_version": readme["current"],
        "manifest_seed_count": summary["seed_count"],
        "template_count": template_count,
        # Certification records only: the manifest and the frozen recordings also ship
        # with the library, but they are not acceptance evidence.
        "panel_certification_count": sum(
            1 for path in panel_files if panel_profiles.CERTIFICATIONS in path.as_posix()
        ),
    }


def _release_version_tuple(version: str) -> tuple[int, int, int]:
    match = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", version.strip())
    if match is None:
        raise ValueError(f"Release version {version!r} is not MAJOR.MINOR.PATCH")
    return int(match.group(1)), int(match.group(2)), int(match.group(3))


def _postcheck_section(text: str, version: str) -> str | None:
    """The body of ``## v<version>`` in the POSTCHECK file, or ``None``."""
    lines = text.splitlines()
    header = f"## v{version}"
    start = None
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped == header or stripped.startswith((header + " ", header + "（", header + "(")):
            start = index + 1
            break
    if start is None:
        return None
    end = len(lines)
    for index in range(start, len(lines)):
        if lines[index].startswith("## "):
            end = index
            break
    return "\n".join(lines[start:end])


def _declared_version(text: str) -> str | None:
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return None
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        targets = [target for target in node.targets if isinstance(target, ast.Name)]
        if not any(target.id == "VERSION" for target in targets):
            continue
        try:
            value = ast.literal_eval(node.value)
        except ValueError:
            return None
        if isinstance(value, str) and value.strip():
            return value.strip()
    return None


def _work_item_status(backlog: str, work_id: str) -> str | None:
    """The status cell of ``work_id``'s table row in the main backlog."""
    for line in backlog.splitlines():
        stripped = line.strip()
        if not stripped.startswith("|"):
            continue
        cells = [cell.strip() for cell in stripped.strip("|").split("|")]
        if len(cells) < 3 or f"[{work_id}]" not in cells[0]:
            continue
        return cells[2]
    return None


#: Delivery-state vocabulary shared by the backlog, the work cards and the
#: per-ID table. Only these classes may be compared; a technical phrase such as
#: "已实现并实机验收" is not a delivery claim and stays ``other``.
_PARTIAL_MARKERS = ("部分交付", "待验收", "待复现", "已有修复", "观察中", "待核实")
_EXPLANATION_NONE = ("", "—", "-", "无", "无。")


def _status_class(text: str) -> str:
    """Normalize one status phrase to a comparable delivery class."""
    value = text.strip()
    if "其它 agent" in value:
        return "other"
    if "部分交付" in value:
        return "partial"
    if "已交付" in value and ("剩余" in value or "子项" in value):
        return "partial"
    if "已交付" in value or "已完成" in value:
        return "delivered"
    if "开发中" in value:
        return "developing"
    if "未排期" in value or "待规划" in value:
        return "unplanned"
    if any(marker in value for marker in _PARTIAL_MARKERS):
        return "partial"
    return "other"


def _split_row(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _is_separator(cells: list[str]) -> bool:
    return bool(cells) and all(re.fullmatch(r":?-{3,}:?", cell) for cell in cells if cell)


def _id_table(text: str) -> tuple[list[str], list[tuple[str, list[str]]]]:
    """The ``## 逐 ID 状态核对`` header and its ``(id, cells)`` rows."""
    lines = text.splitlines()
    start = None
    for index, line in enumerate(lines):
        if line.strip().startswith("## 逐 ID"):
            start = index + 1
            break
    if start is None:
        return [], []
    header: list[str] = []
    rows: list[tuple[str, list[str]]] = []
    for line in lines[start:]:
        stripped = line.strip()
        if stripped.startswith("## "):
            break
        if not stripped.startswith("|"):
            continue
        cells = _split_row(stripped)
        if not cells:
            continue
        if not header:
            header = cells
            continue
        if _is_separator(cells):
            continue
        match = re.search(r"\b[A-Z]+-\d+\b", cells[0])
        if match is not None:
            rows.append((match.group(0), cells))
    return header, rows


def _cell(header: list[str], cells: list[str], *names: str) -> str:
    for index, title in enumerate(header):
        if any(name in title for name in names) and index < len(cells):
            return cells[index]
    return ""


def _card_summary(card: str) -> str:
    for line in card.splitlines()[:12]:
        if "分类：" in line:
            return line.strip()
    return ""


def _card_status(card: str) -> str:
    """The bold status token on the card's ``分类：`` line.

    Card summaries continue with evidence sentences that often contain
    "已交付" for a sub-item; reading the whole line would misclassify a
    ``待复现`` card as delivered.
    """
    summary = _card_summary(card)
    if not summary:
        return ""
    match = re.search(r"\*\*([^*]+)\*\*", summary)
    return match.group(1) if match is not None else summary.split("。", 1)[0]


def _delivery_snapshot(version: str, read) -> dict | None:
    """The frozen delivery scope for ``version``, or ``None`` before adoption.

    The snapshot is written by a human/agent from the actual changes, the main
    ledger and the work cards, and then frozen. It must never be derived from
    the per-ID table it is used to check.
    """
    name = f"{DELIVERY_SNAPSHOT_DIR}/{version}.json"
    text = read(name)
    if text is None:
        return None
    try:
        document = json.loads(text)
    except ValueError as error:
        raise ValueError(f"{name} is not readable JSON: {error}") from error
    if not isinstance(document, dict):
        raise ValueError(f"{name} is not a JSON object")
    if document.get("schema_version") != DELIVERY_SNAPSHOT_SCHEMA:
        raise ValueError(f"{name} schema_version must be {DELIVERY_SNAPSHOT_SCHEMA}")
    if document.get("version") != version:
        raise ValueError(f"{name} declares version {document.get('version')!r}, expected {version}")
    previous = document.get("previous_version")
    if not isinstance(previous, str):
        raise ValueError(f"{name} has no previous_version")
    try:
        previous_tuple = _release_version_tuple(previous)
        current_tuple = _release_version_tuple(version)
    except ValueError as error:
        raise ValueError(f"{name}: {error}") from error
    if previous_tuple >= current_tuple:
        raise ValueError(f"{name} previous_version {previous} is not older than {version}")
    if document.get("previous_release_tag") != f"v{previous}":
        raise ValueError(
            f"{name} previous_release_tag {document.get('previous_release_tag')!r} must be "
            f"'v{previous}'"
        )
    commit = document.get("previous_release_commit")
    if not isinstance(commit, str) or _COMMIT_PATTERN.fullmatch(commit) is None:
        raise ValueError(f"{name} previous_release_commit must be a 40-character commit id")
    state = document.get("remote_verification")
    if state not in _REMOTE_VERIFICATION_STATES:
        raise ValueError(f"{name} remote_verification must be one of {_REMOTE_VERIFICATION_STATES}")
    ids = document.get("delivery_ids")
    if not isinstance(ids, list) or not ids:
        raise ValueError(f"{name} delivery_ids must be a non-empty list")
    delivery_ids: set[str] = set()
    for item in ids:
        if not isinstance(item, str) or _WORK_ID_PATTERN.fullmatch(item) is None:
            raise ValueError(f"{name} has an invalid delivery id: {item!r}")
        if item in delivery_ids:
            raise ValueError(f"{name} lists delivery id {item} more than once")
        delivery_ids.add(item)
    return {
        "path": name,
        "delivery_ids": delivery_ids,
        "previous_version": previous,
        "previous_release_commit": commit,
        "remote_verification": state,
    }


def release_delivery_ids(version: str, read) -> set[str]:
    """The frozen delivery-ID set for ``version`` (see :func:`_delivery_snapshot`)."""
    snapshot = _delivery_snapshot(version, read)
    if snapshot is None:
        raise ValueError(f"No delivery snapshot exists for {version}: {DELIVERY_SNAPSHOT_DIR}")
    return set(snapshot["delivery_ids"])


def _archived_status(archive: str, work_id: str) -> str | None:
    """The status cell of ``work_id`` in the completion archive, or ``None``."""
    for line in archive.splitlines():
        stripped = line.strip()
        if not stripped.startswith("|"):
            continue
        cells = _split_row(stripped)
        if len(cells) < 3 or _is_separator(cells):
            continue
        if f"[{work_id}]" not in cells[0]:
            continue
        return cells[2]
    return None


def _previous_version_problems(text: str, snapshot: dict, origin: str) -> list[str]:
    """Every ``上一版本：X`` label must name the frozen direct predecessor."""
    problems = []
    seen = False
    for value in _PREVIOUS_VERSION_PATTERN.findall(text):
        seen = True
        if value.lstrip("v") != snapshot["previous_version"]:
            problems.append(
                f"{origin}: 上一版本 {value!r} differs from {snapshot['path']} "
                f"previous_version {snapshot['previous_version']!r}"
            )
    if not seen:
        problems.append(
            f"{origin}: must state '上一版本：{snapshot['previous_version']}' so the comparison "
            f"baseline matches {snapshot['path']}"
        )
    return problems


def _previous_commit_problems(text: str, snapshot: dict, origin: str) -> list[str]:
    """``previous_release_commit`` must match the commit the note itself states.

    A format-only check let a random 40-hex value, or the previous version's
    post-release backfill commit, pass every gate (0.30.0 feedback P2, still open
    in 0.31.1). The release note states the previous version and its commit
    independently, so a value that disagrees with it cannot be the last release
    point. Notes that state no commit keep their historical shape; the tag check
    in :func:`_tag_commit_problems` covers a real checkout.
    """
    stated: list[str] = []
    for line in text.splitlines():
        if "上一版本" in line:
            stated.extend(_COMMIT_PATTERN.findall(line))
    if not stated or snapshot["previous_release_commit"] in stated:
        return []
    return [
        f"{origin}: previous_release_commit {snapshot['previous_release_commit']} differs from "
        f"the commit this note states for the previous version "
        f"({', '.join(sorted(set(stated)))}); the field must name the previous release commit, "
        "not a backfill or an arbitrary id"
    ]


def _tag_commit_problems(version: str, root: Path) -> list[str]:
    """Resolve ``v<previous>`` in this checkout and compare it with the snapshot.

    Only a real checkout can answer this. A missing ``.git``, a missing git
    executable or an absent tag is not proof that the record is wrong, so those
    cases add nothing; the cross-file check keeps working there.
    """
    if not (Path(root) / ".git").exists():
        return []
    name = f"{DELIVERY_SNAPSHOT_DIR}/{version}.json"
    path = Path(root) / name
    if not path.is_file():
        return []
    try:
        snapshot = _delivery_snapshot(version, lambda key: (Path(root) / key).read_text("utf-8"))
    except ValueError:
        return []
    tag = f"v{snapshot['previous_version']}"
    try:
        result = subprocess.run(
            ["git", "-C", str(root), "rev-parse", f"{tag}^{{commit}}"],
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return []
    if result.returncode != 0:
        return []
    actual = result.stdout.strip()
    if actual == snapshot["previous_release_commit"]:
        return []
    return [
        f"source tree: previous_release_commit {snapshot['previous_release_commit']} is not "
        f"{tag} ({actual})"
    ]


def approved_evidence_files(root: Path) -> list[Path]:
    """The TXT evidence files explicitly approved for the source package.

    The packager uses this list instead of widening the ``docs`` allowlist to
    every ``.txt``. Each entry is a repository-relative path with its own byte
    count and SHA256, so a changed or missing file is refused before the ZIP is
    written.
    """
    root = Path(root)
    manifest = root / DISTRIBUTION_EVIDENCE
    if not manifest.is_file() or manifest.is_symlink():
        raise ValueError(f"Distribution evidence manifest is missing: {manifest}")
    document = _read_json(manifest)
    if document.get("schema_version") != 1:
        raise ValueError(f"{DISTRIBUTION_EVIDENCE} schema_version must be 1")
    entries = document.get("files")
    if not isinstance(entries, list) or not entries:
        raise ValueError(f"{DISTRIBUTION_EVIDENCE} names no files")
    files: list[Path] = []
    seen: set[str] = set()
    for entry in entries:
        if not isinstance(entry, dict):
            raise ValueError(f"{DISTRIBUTION_EVIDENCE} has an entry that is not an object")
        name = entry.get("path")
        if not isinstance(name, str) or not name:
            raise ValueError(f"{DISTRIBUTION_EVIDENCE} has an entry without a path")
        relative = PurePosixPath(name)
        if (
            relative.is_absolute()
            or ".." in relative.parts
            or "\\" in name
            or relative.suffix != ".txt"
            or not relative.parts
            or relative.parts[0] != "docs"
        ):
            raise ValueError(
                f"{DISTRIBUTION_EVIDENCE} has an unsafe or non-TXT evidence path: {name!r}"
            )
        if name in seen:
            raise ValueError(f"{DISTRIBUTION_EVIDENCE} names {name} more than once")
        seen.add(name)
        target = root / name
        if not target.is_file() or target.is_symlink():
            raise ValueError(f"Approved evidence file is missing or is a symlink: {target}")
        data = target.read_bytes()
        declared_bytes = entry.get("bytes")
        if not isinstance(declared_bytes, int) or declared_bytes != len(data):
            raise ValueError(
                f"Approved evidence {name} is {len(data)} bytes but the manifest declares "
                f"{declared_bytes}"
            )
        declared = entry.get("sha256")
        if not isinstance(declared, str) or _DIGEST_PATTERN.fullmatch(declared) is None:
            raise ValueError(f"{DISTRIBUTION_EVIDENCE} has no valid sha256 for {name}")
        digest = hashlib.sha256(data).hexdigest()
        if digest != declared:
            raise ValueError(
                f"Approved evidence {name} is {digest} but the manifest declares {declared}; "
                "update the archive instead of shipping changed bytes"
            )
        files.append(target)
    return files


def _distribution_problems(read, origin: str) -> list[str]:
    """Structure and presence of the approved TXT evidence list.

    Digest and byte checks need the real tree and belong to
    :func:`approved_evidence_files`; this variant also runs against ``source.zip``
    members, where only presence is knowable.
    """
    text = read(DISTRIBUTION_EVIDENCE)
    if text is None:
        return [f"{origin}: missing {DISTRIBUTION_EVIDENCE}"]
    try:
        document = json.loads(text)
    except ValueError:
        return [f"{origin}: {DISTRIBUTION_EVIDENCE} is not readable JSON"]
    if not isinstance(document, dict) or document.get("schema_version") != 1:
        return [f"{origin}: {DISTRIBUTION_EVIDENCE} schema_version must be 1"]
    entries = document.get("files")
    if not isinstance(entries, list) or not entries:
        return [f"{origin}: {DISTRIBUTION_EVIDENCE} names no files"]
    problems = []
    seen: set[str] = set()
    for entry in entries:
        name = entry.get("path") if isinstance(entry, dict) else None
        if not isinstance(name, str) or not name:
            problems.append(f"{origin}: {DISTRIBUTION_EVIDENCE} has an entry without a path")
            continue
        relative = PurePosixPath(name)
        if (
            relative.is_absolute()
            or ".." in relative.parts
            or "\\" in name
            or relative.suffix != ".txt"
            or not relative.parts
            or relative.parts[0] != "docs"
        ):
            problems.append(
                f"{origin}: {DISTRIBUTION_EVIDENCE} has an unsafe or non-TXT path {name!r}"
            )
            continue
        if name in seen:
            problems.append(f"{origin}: {DISTRIBUTION_EVIDENCE} names {name} more than once")
            continue
        seen.add(name)
        if not read(name):
            problems.append(f"{origin}: approved evidence {name} is missing")
    return problems


def _backlog_rows(backlog: str) -> list[tuple[str, list[str]]]:
    """``[ID](work-items/...)`` rows of the main backlog with at least 3 cells."""
    rows: list[tuple[str, list[str]]] = []
    for line in backlog.splitlines():
        stripped = line.strip()
        if not stripped.startswith("|"):
            continue
        cells = _split_row(stripped)
        if len(cells) < 3 or _is_separator(cells):
            continue
        if "work-items/" not in cells[0]:
            continue
        match = re.search(r"\[([A-Z]+-\d+)\]", cells[0])
        if match is not None:
            rows.append((match.group(1), cells))
    return rows


def _record_problems(
    text: str,
    version: str,
    origin: str,
    seed_digest: str | None,
    *,
    require_sidecar_note: bool,
    snapshot: dict | None = None,
) -> list[str]:
    """Problems in one POSTCHECK section or ``RELEASE-<version>.md`` record."""
    problems = []
    for name in expected_assets(version):
        if name not in text:
            problems.append(f"{origin}: missing release asset {name}")
    release_url = f"https://github.com/wudahua/MCP_CREO_MechDog/releases/tag/v{version}"
    if release_url not in text:
        problems.append(f"{origin}: missing Release URL {release_url}")
    if seed_digest is None:
        problems.append(f"{origin}: no trusted seed archive SHA256 to match")
    elif seed_digest not in text:
        problems.append(f"{origin}: missing seed archive SHA256 {seed_digest}")
    if _DIGEST_PATTERN.search(text) is None:
        problems.append(f"{origin}: missing a 64-character SHA256")
    for placeholder in _PLACEHOLDERS:
        if placeholder in text:
            problems.append(f"{origin}: contains placeholder {placeholder!r}")
    if require_sidecar_note and not re.search(
        r"摘要[^\n]{0,24}sidecar|sidecar[^\n]{0,24}摘要", text
    ):
        problems.append(f"{origin}: must state that the source.zip digest is in its sidecar")
    if snapshot is not None and snapshot["remote_verification"] == "pending":
        # A package frozen before publication cannot know the remote result.
        # Writing the later `exit 0` into the packaged snapshot is the P3-5
        # pattern from the 0.25.0 feedback.
        claim = _REMOTE_CLAIM.search(text)
        if claim is not None:
            problems.append(
                f"{origin}: claims remote verification {claim.group(0).strip()!r}, but "
                f"{snapshot['path']} declares remote_verification='pending'; write "
                f"'{_REMOTE_VERIFIED_NOTE}' instead"
            )
    return problems


def _link_problems(text: str, origin: str, base_dir: str, exists) -> list[str]:
    """Broken relative links in one published document.

    Only file existence is checked; anchors and external URLs are skipped. A
    link that walks above the package root is rejected so ``../../outside`` can
    never pass on the author's machine.
    """
    problems = []
    for target in _LINK_PATTERN.findall(text):
        if target.startswith(("http://", "https://", "mailto:", "#", "/")):
            continue
        path = target.split("#", 1)[0].strip("<>")
        if not path:
            continue
        parts: list[str] | None = []
        for part in f"{base_dir}/{path}".split("/"):
            if part in ("", "."):
                continue
            if part == "..":
                if not parts:
                    problems.append(f"{origin}: link {target!r} escapes the package")
                    parts = None
                    break
                parts.pop()
            else:
                parts.append(part)
        if parts is None:
            continue
        name = "/".join(parts)
        if not exists(name):
            problems.append(f"{origin}: broken local link {target!r} -> {name}")
    return problems


def _work_item_problems(version: str, record: str, read, origin: str) -> list[str]:
    """Cross-check the release's per-ID table and every active delivery row.

    From the first version with a frozen delivery snapshot the table's ID set
    must equal that snapshot, its ``交付版本``/``实际 Release`` columns must name
    this release, and a difference note may no longer excuse a literal main
    ledger mismatch. IDs already moved to the completion archive stay valid.
    """
    backlog = read("docs/BACKLOG.md")
    if backlog is None:
        return [f"{origin}: missing docs/BACKLOG.md for the per-ID check"]
    header, rows = _id_table(record)
    if not rows:
        return [f"{origin}: RELEASE-{version}.md has no '逐 ID 状态核对' table rows"]
    try:
        snapshot = _delivery_snapshot(version, read)
    except ValueError as error:
        return [f"{origin}: {error}"]
    problems = []
    if snapshot is not None:
        for column in ("交付版本", "实际 Release"):
            if not any(column in title for title in header):
                problems.append(
                    f"{origin}: the per-ID table has no {column!r} column required by "
                    f"{snapshot['path']}"
                )
    archive = read(COMPLETION_ARCHIVE) or ""
    checked = set()
    for work_id, cells in rows:
        checked.add(work_id)
        status = _work_item_status(backlog, work_id)
        archived_status = None
        if status is None:
            archived_status = _archived_status(archive, work_id)
            status = archived_status
        if status is None:
            problems.append(
                f"{origin}: {work_id} is missing from docs/BACKLOG.md and {COMPLETION_ARCHIVE}"
            )
            continue
        card = read(f"docs/work-items/{work_id}.md") or read(
            f"docs/archive/work-items/{work_id}.md"
        )
        if card is None:
            problems.append(f"{origin}: missing docs/work-items/{work_id}.md")
            continue
        if archived_status is None and version not in "\n".join(card.splitlines()[:12]):
            problems.append(
                f"{origin}: docs/work-items/{work_id}.md first 12 lines do not mention {version}"
            )
        explanation = _cell(header, cells, "差异说明")
        explained = explanation.strip() not in _EXPLANATION_NONE
        backlog_class = _status_class(status)
        if snapshot is not None:
            delivery = _cell(header, cells, "交付版本")
            if delivery.strip() != version:
                problems.append(
                    f"{origin}: {work_id} 交付版本 {delivery!r} must be exactly {version}"
                )
            released = _cell(header, cells, "实际 Release")
            if released.strip() != f"v{version}":
                problems.append(f"{origin}: {work_id} 实际 Release {released!r} must be v{version}")
            if archived_status is not None and backlog_class not in ("delivered", "partial"):
                problems.append(
                    f"{origin}: {work_id} is archived as {archived_status!r}, which is not a "
                    "delivered class; an unknown state is never read as delivered"
                )
        if archived_status is None:
            for title in ("技术状态", "卡首页"):
                value = _cell(header, cells, title)
                if not value or _status_class(value) == "other":
                    continue
                if _status_class(value) != backlog_class and not explained:
                    problems.append(
                        f"{origin}: {work_id} {title} {value!r} differs from "
                        f"docs/BACKLOG.md {status!r}"
                    )
            summary = _card_summary(card)
            if not summary:
                problems.append(
                    f"{origin}: docs/work-items/{work_id}.md has no '分类：' line in its first "
                    "12 lines"
                )
            elif _status_class(_card_status(card)) != backlog_class and not explained:
                problems.append(
                    f"{origin}: work card {work_id} says {summary!r} but docs/BACKLOG.md "
                    f"says {status!r}"
                )
        # A note may explain a conservative status-class difference, never an
        # identity/version/link error: the main ledger cell stays literal.
        ledger_cell = _cell(header, cells, "主台账")
        ledger_excused = explained and snapshot is None
        if ledger_cell and ledger_cell.strip() != status.strip() and not ledger_excused:
            problems.append(
                f"{origin}: {work_id} 主台账 cell {ledger_cell!r} differs from "
                f"{_ledger_name(archived_status)} {status!r}"
            )
        if f"已交付 {version}" in " | ".join(cells) and backlog_class in (
            "developing",
            "unplanned",
        ):
            problems.append(
                f"{origin}: {work_id} claims 已交付 {version} but the ledger says {status}"
            )
    if snapshot is not None:
        expected = set(snapshot["delivery_ids"])
        missing = sorted(expected - checked)
        extra = sorted(checked - expected)
        if missing:
            problems.append(
                f"{origin}: per-ID table is missing frozen delivery id(s) {missing} from "
                f"{snapshot['path']}"
            )
        if extra:
            problems.append(
                f"{origin}: per-ID table lists id(s) {extra} that are not in the frozen "
                f"delivery set {snapshot['path']}"
            )
    for work_id, cells in _backlog_rows(backlog):
        if work_id in checked:
            continue
        status = cells[2]
        backlog_class = _status_class(status)
        if backlog_class not in ("partial", "delivered", "developing", "unplanned"):
            continue
        card = read(f"docs/work-items/{work_id}.md") or read(
            f"docs/archive/work-items/{work_id}.md"
        )
        if card is None:
            if backlog_class in ("partial", "delivered"):
                problems.append(
                    f"{origin}: docs/work-items/{work_id}.md is missing for a {status!r} row"
                )
            continue
        summary = _card_summary(card)
        if not summary:
            continue
        card_class = _status_class(_card_status(card))
        if backlog_class in ("partial", "delivered") and card_class != backlog_class:
            problems.append(
                f"{origin}: work card {work_id} says {summary!r} but docs/BACKLOG.md "
                f"says {status!r}"
            )
        elif backlog_class in ("developing", "unplanned") and card_class == "delivered":
            problems.append(
                f"{origin}: work card {work_id} says {summary!r} but docs/BACKLOG.md still "
                f"says {status!r}"
            )
    return problems


def _ledger_name(archived_status: str | None) -> str:
    return COMPLETION_ARCHIVE if archived_status is not None else "docs/BACKLOG.md"


def _version_problems(version: str, read, origin: str) -> list[str]:
    """The package's own version declarations must all agree."""
    problems = []
    source = read("version.py")
    if source is None:
        problems.append(f"{origin}: missing version.py")
    else:
        declared = _declared_version(source)
        if declared != version:
            problems.append(f"{origin}: version.py declares {declared}, expected {version}")
    readme = read("README.md")
    if readme is None:
        problems.append(f"{origin}: missing README.md")
    else:
        title = _README_TITLE_PATTERN.search(readme)
        current = _README_CURRENT_PATTERN.search(readme)
        if title is None or title.group(1) != version:
            problems.append(f"{origin}: README title is not {version}")
        if current is None or current.group(1) != version:
            problems.append(f"{origin}: README current release section is not {version}")
    for name in (DOCUMENTATION_MANIFEST, f"{SEED_LIBRARY}/{SEED_MANIFEST}"):
        text = read(name)
        if text is None:
            problems.append(f"{origin}: missing {name}")
            continue
        try:
            manifest = json.loads(text)
        except ValueError:
            problems.append(f"{origin}: {name} is not readable JSON")
            continue
        declared = manifest.get("compatible_server_version")
        if declared != version:
            problems.append(f"{origin}: {name} declares {declared}, expected {version}")
    return problems


def _records_problems(version: str, read, exists, origin: str) -> list[str]:
    problems = _version_problems(version, read, origin)
    try:
        snapshot = _delivery_snapshot(version, read)
    except ValueError as error:
        problems.append(f"{origin}: {error}")
        snapshot = None
    if snapshot is not None:
        problems.extend(_distribution_problems(read, origin))
    seed_digest = None
    record = read(TRUSTED_RECORD)
    if record is None:
        problems.append(f"{origin}: missing {TRUSTED_RECORD}")
    else:
        try:
            seed_digest = json.loads(record).get("seed_archive_sha256")
        except ValueError:
            problems.append(f"{origin}: {TRUSTED_RECORD} is not readable JSON")
        if not isinstance(seed_digest, str) or _DIGEST_PATTERN.fullmatch(seed_digest) is None:
            problems.append(f"{origin}: {TRUSTED_RECORD} has no valid seed_archive_sha256")
            seed_digest = None
    postcheck = read(POSTCHECK)
    if postcheck is None:
        problems.append(f"{origin}: missing {POSTCHECK}")
    else:
        problems.extend(
            _link_problems(postcheck, f"{origin}:{POSTCHECK}", "docs/development", exists)
        )
        section = _postcheck_section(postcheck, version)
        if section is None:
            problems.append(f"{origin}: {POSTCHECK} has no '## v{version}' section")
        else:
            problems.extend(
                _record_problems(
                    section,
                    version,
                    f"{origin}:POSTCHECK v{version}",
                    seed_digest,
                    require_sidecar_note=False,
                    snapshot=snapshot,
                )
            )
    notes_base = "docs/release-notes"
    notes = read(f"docs/release-notes/RELEASE_NOTES_{version}.md")
    if notes is None:
        legacy_notes = read(f"docs/RELEASE_NOTES_{version}.md")
        if legacy_notes is not None:
            notes = legacy_notes
            notes_base = "docs"
    if notes is None:
        problems.append(f"{origin}: missing docs/release-notes/RELEASE_NOTES_{version}.md")
    elif snapshot is not None:
        problems.extend(
            _previous_version_problems(notes, snapshot, f"{origin}:RELEASE_NOTES_{version}.md")
        )
    if notes is not None:
        problems.extend(
            _link_problems(notes, f"{origin}:RELEASE_NOTES_{version}.md", notes_base, exists)
        )
    release = read(f"docs/validation/RELEASE-{version}.md")
    if release is None:
        problems.append(f"{origin}: missing docs/validation/RELEASE-{version}.md")
    else:
        problems.extend(
            _record_problems(
                release,
                version,
                f"{origin}:RELEASE-{version}.md",
                seed_digest,
                require_sidecar_note=True,
                snapshot=snapshot,
            )
        )
        problems.extend(
            _link_problems(release, f"{origin}:RELEASE-{version}.md", "docs/validation", exists)
        )
        if snapshot is not None:
            problems.extend(
                _previous_version_problems(release, snapshot, f"{origin}:RELEASE-{version}.md")
            )
            problems.extend(
                _previous_commit_problems(release, snapshot, f"{origin}:RELEASE-{version}.md")
            )
            if (
                snapshot["remote_verification"] == "pending"
                and _REMOTE_VERIFIED_NOTE not in release
            ):
                problems.append(
                    f"{origin}:RELEASE-{version}.md must state '{_REMOTE_VERIFIED_NOTE}' "
                    f"while {snapshot['path']} declares remote_verification='pending'"
                )
        problems.extend(_work_item_problems(version, release, read, origin))
    return problems


_UNIT_TEST_REPORT = "build/unit_test_report.json"
# A positive claim that the full unittest suite passed. Lines that negate the
# claim ("不宣称全量通过", "未跑全量") are not claims and must not require a
# success report; otherwise a record that honestly says it did not run would be
# forced to invent passing numbers (BUG-137).
_FULL_UNIT_PASS_PATTERN = re.compile(
    r"全量[^\n。；;]{0,40}(?:unittest|单测)[^\n。；;]{0,40}通过"
    r"|全量[^\n。；;]{0,12}通过"
)
_UNIT_PASS_NEGATION = (
    "不宣称",
    "不声称",
    "不能声称",
    "不能算",
    "不算",
    "未跑",
    "未复现",
    "未测",
    "冒充",
)


def _read_text_optional(path: Path) -> str | None:
    try:
        return Path(path).read_text(encoding="utf-8-sig")
    except OSError:
        return None


def _has_full_unit_pass_claim(text: str) -> bool:
    for line in text.splitlines():
        if any(marker in line for marker in _UNIT_PASS_NEGATION):
            continue
        if _FULL_UNIT_PASS_PATTERN.search(line):
            return True
    return False


def _load_unit_report(path: Path) -> dict | None:
    text = _read_text_optional(path)
    if text is None:
        return None
    try:
        document = json.loads(text)
    except ValueError:
        return None
    return document if isinstance(document, dict) else None


def _unit_report_summary(report: dict | None) -> str:
    if not isinstance(report, dict):
        return "report unavailable"
    return (
        f"success={report.get('success')!r}, tests_run={report.get('tests_run')!r}, "
        f"failures={report.get('failures')!r}, errors={report.get('errors')!r}, "
        f"skipped={report.get('skipped')!r}, run_id={report.get('run_id')!r}"
    )


def _unit_run_problems(version: str, base: Path, report_file: Path, report: dict) -> list[str]:
    """Reject a success report that is not this round's completed evidence."""
    state_file = unit_evidence.run_state_path(report_file)
    state = unit_evidence.load_run(report_file)
    prefix = "source tree: release record claims 全量 unittest 通过 but "
    if state is None:
        return [
            f"{prefix}{state_file.name} is missing or unreadable; a success report "
            "alone is not proof of the current round. Run tools/test_unit.py for "
            "this round and confirm it completed"
        ]
    if state.get("schema_version") != unit_evidence.SCHEMA_VERSION:
        return [
            f"{prefix}{state_file.name} schema_version is "
            f"{state.get('schema_version')!r}, expected "
            f"{unit_evidence.SCHEMA_VERSION}"
        ]
    status = state.get("status")
    if status != "completed":
        return [
            f"{prefix}the current unit run is {status!r}, not completed "
            f"(run_id={state.get('run_id')!r}); a previous success report is not "
            "accepted. Wait for tools/test_unit.py to finish"
        ]
    if state.get("success") is not True:
        return [
            f"{prefix}the current unit run reports success={state.get('success')!r} "
            f"(run_id={state.get('run_id')!r}); do not write 全量通过 until "
            "tools/test_unit.py reports success=true"
        ]
    if state.get("version") != version:
        return [
            f"{prefix}the current unit run is for version "
            f"{state.get('version')!r}, expected {version}"
        ]
    if report.get("version") != version:
        return [f"{prefix}the report is for version {report.get('version')!r}, expected {version}"]
    run_id = report.get("run_id")
    if not run_id or state.get("run_id") != run_id:
        return [
            f"{prefix}the report run_id {run_id!r} does not belong to the current "
            f"run {state.get('run_id')!r}; regenerate the report"
        ]
    report_source = report.get("source") or {}
    state_source = state.get("source") or {}
    if (
        report_source.get("source_status") != "complete"
        or state_source.get("source_status") != "complete"
    ):
        return [
            f"{prefix}the report or run state source_status is not complete "
            f"(report={report_source.get('source_status')!r}, "
            f"state={state_source.get('source_status')!r})"
        ]
    try:
        current = local_provenance(Path(base))
    except Exception as error:  # pragma: no cover - defensive boundary
        return [f"{prefix}cannot compute the tested source fingerprint: {error}"]
    fingerprint = current.get("source_fingerprint")
    if not fingerprint:
        return [f"{prefix}the tested source fingerprint is unavailable"]
    problems = []
    for label, source in (("report", report_source), ("run state", state_source)):
        actual = source.get("source_fingerprint")
        if actual != fingerprint:
            problems.append(
                f"{prefix}the {label} source fingerprint {actual!r} does not match "
                f"the tested source {fingerprint}"
            )
    if int(report.get("tests_run") or 0) <= 0:
        problems.append(f"{prefix}the report records tests_run=0")
    return problems


def _unit_test_claim_problems(
    version: str, base: Path, unit_report: Path | None = None
) -> list[str]:
    """A "全量通过" release claim must be backed by this round's success report.

    The real failures/errors/skipped counts are printed so the operator sees
    them instead of trusting the record's prose; a claim without a passing
    report is refused (BUG-137). From :data:`UNIT_EVIDENCE_ENFORCED_FROM` the
    report must also match the completed run state and the tested source
    fingerprint, so a stale report cannot back a new release (BUG-144).
    """
    record = _read_text_optional(Path(base) / f"docs/validation/RELEASE-{version}.md")
    notes = _read_text_optional(
        Path(base) / f"docs/release-notes/RELEASE_NOTES_{version}.md"
    ) or _read_text_optional(Path(base) / f"docs/RELEASE_NOTES_{version}.md")
    if not (_has_full_unit_pass_claim(record or "") or _has_full_unit_pass_claim(notes or "")):
        return []
    report_file = Path(unit_report) if unit_report is not None else Path(base) / _UNIT_TEST_REPORT
    report = _load_unit_report(report_file)
    print(
        f"[release-gate] {version} unit test report: {_unit_report_summary(report)}",
        file=sys.stderr,
    )
    if report is None:
        return [
            "source tree: release record claims 全量 unittest 通过 but "
            f"{report_file} is missing or unreadable; run tools/test_unit.py "
            "and confirm success=true before writing 全量通过"
        ]
    if report.get("success") is not True:
        return [
            "source tree: release record claims 全量 unittest 通过 but "
            f"{report_file.name} reports {_unit_report_summary(report)}; "
            "do not write 全量通过 until tools/test_unit.py reports success=true"
        ]
    try:
        enforced = _release_version_tuple(version) >= UNIT_EVIDENCE_ENFORCED_FROM
    except ValueError:
        enforced = False
    if enforced:
        return _unit_run_problems(version, base, report_file, report)
    return []


def validate_release_records(
    version: str,
    source_zip: Path | None = None,
    root: Path | None = None,
    unit_report: Path | None = None,
) -> list[str]:
    """Problems that keep ``version`` from being packaged or published.

    DEV-083: 0.22.0 and 0.23.0 were tagged before their POSTCHECK and release
    records were backfilled, so the distributed ``source.zip`` carried a
    placeholder. From :data:`RECORDS_ENFORCED_FROM` on, the packager refuses to
    write such an archive and the remote check refuses to accept one. When
    ``source_zip`` is given, the same checks run against the archive's own copies
    and its version declarations must agree with ``version``. Versions before the
    enforcement point return no problems; their historical tags only get the
    four-asset check.
    """
    try:
        enforced = _release_version_tuple(version) >= RECORDS_ENFORCED_FROM
    except ValueError as error:
        return [str(error)]
    if not enforced:
        return []
    base: Path | None = None
    if root is not None:
        base = Path(root)
    elif source_zip is None:
        base = Path(__file__).resolve().parents[2]

    def read_tree(name: str) -> str | None:
        path = Path(base) / name
        if not path.is_file():
            return None
        return path.read_text(encoding="utf-8-sig")

    def exists_tree(name: str) -> bool:
        return (Path(base) / name).is_file()

    problems = (
        [] if base is None else _records_problems(version, read_tree, exists_tree, "source tree")
    )
    if base is not None:
        # 0.30.0 feedback P2: a real checkout can resolve the previous tag, which
        # is the only independent proof that the recorded commit is the release
        # point rather than a backfill or an arbitrary 40-hex value.
        problems.extend(_tag_commit_problems(version, base))
        # BUG-137/BUG-144: a "全量通过" release claim must be backed by a
        # success=true report from the run that just completed; build/ is not
        # packaged, so this only runs against the source tree.
        problems.extend(_unit_test_claim_problems(version, base, unit_report))
    if base is not None and (base / DELIVERY_SNAPSHOT_DIR / f"{version}.json").is_file():
        # Byte-exact TXT distribution: a changed or missing approved file is a
        # packaging error, not a documentation note. Versions without a delivery
        # snapshot predate this rule and keep their historical checks.
        try:
            approved_evidence_files(base)
        except ValueError as error:
            problems.append(f"source tree: {error}")
    if source_zip is None:
        return problems
    archive_path = Path(source_zip)
    try:
        with zipfile.ZipFile(archive_path) as archive:
            members = archive_members(archive)
    except (OSError, zipfile.BadZipFile) as error:
        return problems + [f"source.zip is not a readable ZIP: {error}"]
    prefix = f"{RELEASE_ASSET_NAME}/"

    def read_archive(name: str) -> str | None:
        data = members.get(prefix + name)
        return None if data is None else data.decode("utf-8-sig")

    def exists_archive(name: str) -> bool:
        return prefix + name in members

    return problems + _records_problems(
        version, read_archive, exists_archive, f"{archive_path.name}"
    )


def _postcheck_verified_subsection(text: str, version: str) -> str | None:
    """The body of ``### v<version> 发布后核对`` in the POSTCHECK file, or ``None``."""
    heading = re.compile(rf"^###\s+v{re.escape(version)}\s+发布后核对\s*$", re.MULTILINE)
    match = heading.search(text)
    if match is None:
        return None
    rest = text[match.end() :]
    next_heading = re.search(r"^#{2,3}\s+", rest, re.MULTILINE)
    return rest if next_heading is None else rest[: next_heading.start()]


def validate_post_release_backfill(version: str, root: Path | None = None) -> list[str]:
    """Verify post-release backfill evidence on a source tree after publishing."""
    try:
        _release_version_tuple(version)
    except ValueError as error:
        return [str(error)]
    base = Path(root) if root is not None else Path(__file__).resolve().parents[2]
    problems: list[str] = []

    snapshot_file = base / DELIVERY_SNAPSHOT_DIR / f"{version}.json"
    if not snapshot_file.is_file():
        problems.append(f"source tree: missing {DELIVERY_SNAPSHOT_DIR}/{version}.json")
    else:
        try:
            snapshot = json.loads(snapshot_file.read_text(encoding="utf-8-sig"))
        except (OSError, ValueError):
            problems.append(
                f"source tree: {DELIVERY_SNAPSHOT_DIR}/{version}.json is not readable JSON"
            )
        else:
            remote_status = (
                snapshot.get("remote_verification") if isinstance(snapshot, dict) else None
            )
            if remote_status != "verified":
                problems.append(
                    f"source tree: {DELIVERY_SNAPSHOT_DIR}/{version}.json remote_verification "
                    f"must be 'verified' after release, got {remote_status!r}"
                )

    postcheck_file = base / POSTCHECK
    if not postcheck_file.is_file():
        problems.append(f"source tree: missing {POSTCHECK}")
        return problems
    postcheck_text = postcheck_file.read_text(encoding="utf-8-sig")
    subsection = _postcheck_verified_subsection(postcheck_text, version)
    if subsection is None:
        problems.append(f"source tree: {POSTCHECK} has no '### v{version} 发布后核对' section")
        return problems

    if re.search(r"Release\s+`?\d+`?", subsection) is None:
        problems.append(
            f"source tree: POSTCHECK ### v{version} 发布后核对 must record Release numeric id"
        )
    if "退出码 0" not in subsection and "exit 0" not in subsection:
        problems.append(
            f"source tree: POSTCHECK ### v{version} 发布后核对 must record '退出码 0' or 'exit 0'"
        )
    if re.search(r"\b[0-9a-f]{40}\b", subsection) is None:
        problems.append(
            f"source tree: POSTCHECK ### v{version} 发布后核对 must record a 40-hex commit hash"
        )
    for asset_name in expected_assets(version):
        if asset_name not in subsection:
            problems.append(
                f"source tree: POSTCHECK ### v{version} 发布后核对 is missing asset {asset_name!r}"
            )
    digests = re.findall(r"\b[0-9a-f]{64}\b", subsection)
    if len(digests) < 2:
        problems.append(
            f"source tree: POSTCHECK ### v{version} 发布后核对 must record SHA256 digests for "
            "both ZIP assets"
        )
    return problems
